def load_json(rel):
    p = ROOT / rel
    if not p.exists():
        return None
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def yolo_last(name):
    import pandas as pd
    p = ROOT / "results" / name / "results.csv"
    if not p.exists():
        return None
    return pd.read_csv(p).iloc[-1]


def pct(x, nd=1):
    if x is None:
        return "—"
    return f"{x*100:.{nd}f}%"


def fmt(x, nd=3):
    if x is None:
        return "—"
    return f"{x:.{nd}f}"


