                 "与手工设计特征，泛化能力有限；随着深度学习的发展，以 CNN 为骨干的分类网络（如 ResNet）在图像级缺陷判别上"
                 "取得了显著进展，而以 YOLO 系列、Faster R-CNN 为代表的目标检测网络则在缺陷定位与多类别识别上表现出色。"
