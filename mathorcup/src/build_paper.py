def _toc_title(doc, text):
    """目录页标题：居中加粗，不强制分页（分页由前置显式分页符控制）。"""
    p = pf.paragraph(doc, align=pf.WD_ALIGN_PARAGRAPH.CENTER)
    pf.set_run_font(p.add_run(text), size=16, bold=True)
    return p


def _heading1_flow(doc, text):
    """一级标题（无强制分页），用于分节后正文起始标题，避免与分节符叠加产生空白页。"""
    p = pf.paragraph(doc, align=pf.WD_ALIGN_PARAGRAPH.CENTER)
    pf.set_run_font(p.add_run(text), size=16, bold=True)
    return p


def _add_page_number_footer(doc, start=1):
    """为最后一个 section 的页脚添加居中阿拉伯数字页码，并从 start 开始编号。"""
    section = doc.sections[-1]
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = pf.WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    fld_begin = pf.OxmlElement("w:fldChar")
    fld_begin.set(pf.qn("w:fldCharType"), "begin")
    instr = pf.OxmlElement("w:instrText")
    instr.set(pf.qn("xml:space"), "preserve")
    instr.text = "PAGE"
    fld_end = pf.OxmlElement("w:fldChar")
    fld_end.set(pf.qn("w:fldCharType"), "end")
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_end)
    pf.set_run_font(run, size=10)
    # 按 CT_SectPr 顺序插入 pgNumType（应位于 cols/docGrid 之前），使正文页码从 start 起
    sect_pr = section._sectPr
    pg_num_type = pf.OxmlElement("w:pgNumType")
    pg_num_type.set(pf.qn("w:start"), str(start))
    for tag in ("w:cols", "w:docGrid", "w:printerSettings"):
        anchor = sect_pr.find(pf.qn(tag))
        if anchor is not None:
            anchor.addprevious(pg_num_type)
            break
    else:
        sect_pr.append(pg_num_type)


